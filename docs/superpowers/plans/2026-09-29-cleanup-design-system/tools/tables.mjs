// Renders the maps in ../maps as the tables in ../mapping-*.md, so the tables a person reads are
// the tables the tools apply and not a second copy somebody typed.
//
//   node docs/superpowers/plans/2026-09-29-cleanup-design-system/tools/tables.mjs
//
// Counts of reads are taken from the tree at BASE, the commit the plan was written against, so
// the output is the same whenever it is run.
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const BASE = "5c07c97";
const HERE = path.dirname(fileURLToPath(import.meta.url));
const MAPS = path.join(HERE, "../maps");
const map = (name) => JSON.parse(readFileSync(path.join(MAPS, `${name}.json`), "utf8"));
const at = (file) => execFileSync("git", ["show", `${BASE}:${file}`], { encoding: "utf8" });
const cell = (text) => `\`${String(text).replace(/\|/g, "\\|")}\``;
const table = (head, rows) =>
  [
    `| ${head.join(" | ")} |`,
    `| ${head.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ].join("\n");
const generated = (what) =>
  `<!-- Generated by tools/tables.mjs from ${what}. Do not edit by hand: edit the map and run the script. -->`;

/** A `retoken` map as rows, with how often each name is read in the file at BASE. */
function renames(name, file) {
  const css = at(file);
  return Object.entries(map(name)).map(([from, to]) => {
    const reads = css.match(new RegExp(`var\\(\\s*${from}\\s*\\)`, "g")) ?? [];
    return [cell(from), cell(to), String(reads.length)];
  });
}

/** A `reline` map as rows: for each edit, the lines that go and the lines that come. */
function edits(name) {
  return map(name).map(({ find, replace, count = 1 }) => {
    const was = find.split("\n");
    const is = replace.split("\n");
    const gone = was.filter((line) => line.trim() && !is.includes(line));
    const come = is.filter((line) => line.trim() && !was.includes(line));
    const show = (lines) =>
      lines.length
        ? lines.map((line) => cell(line.trim().slice(0, 110))).join("<br>")
        : "(nothing)";
    return [
      show(gone.length ? gone : was.filter((line) => line.trim())),
      show(come),
      String(count),
    ];
  });
}

const ALIASES = [
  ["10-agents-aliases", "apps/web/src/features/agents/agents.module.css", 10],
  ["11-auth-aliases", "apps/web/src/features/auth/auth.module.css", 11],
  ["12-markets-aliases", "apps/web/src/features/markets/markets.module.css", 12],
  ["13-apply-aliases", "apps/web/src/features/apply/apply.module.css", 13],
];
const VARIANTS = [
  ["11-auth-variants", "apps/web/src/features/auth/auth.module.css", 11],
  ["12-markets-variants", "apps/web/src/features/markets/markets.module.css", 12],
  ["14-landing-variants", "apps/web/src/features/landing/landing.module.css", 14],
  ["14-create-variants", "apps/web/src/features/studio/create/create.module.css", 14],
  ["14-home-variants", "apps/web/src/features/studio/home/home.module.css", 14],
];

const aliases = [
  "# Mapping: aliases and variant variables (batch C)",
  "",
  generated("maps/*-aliases.json and maps/*-variants.json"),
  "",
  "## Plain aliases",
  "",
  "Each alias is defined once on the module's root class and read only inside that module. The",
  "definition is deleted and every read takes the token. `Reads` is counted in the file at",
  `\`${BASE}\`.`,
  ...ALIASES.flatMap(([name, file, task]) => [
    "",
    `### \`${file}\` — task ${task}, \`maps/${name}.json\``,
    "",
    table(["Alias", "Token", "Reads"], renames(name, file)),
  ]),
  "",
  "## Variant variables",
  "",
  "A variable that holds a colour chosen by a `data-*` attribute or a modifier class becomes one",
  "rule per variant (J14). Each row is one edit: the lines that go, the lines that come, and how",
  "many times the text occurs. The edits apply to the file as the alias step leaves it.",
  ...VARIANTS.flatMap(([name, file, task]) => [
    "",
    `### \`${file}\` — task ${task}, \`maps/${name}.json\``,
    "",
    table(["Goes", "Comes", "Times"], edits(name)),
  ]),
  "",
].join("\n");
writeFileSync(path.join(HERE, "../mapping-aliases.md"), aliases);

const expected = map("legacy-expected");
const legacy = [
  "# Mapping: legacy tokens (batch D)",
  "",
  generated("maps/legacy.json and maps/legacy-expected.json"),
  "",
  "## The fourteen that go",
  "",
  "Every `var(--from)` becomes `var(--to)`, in every file. The token on the right is what the",
  "definition on the left already resolved to on both surfaces, so no pixel moves.",
  "",
  table(
    ["Legacy token", "v2 token"],
    Object.entries(map("legacy")).map(([from, to]) => [cell(from), cell(to)]),
  ),
  "",
  "## The seven that stay",
  "",
  "`--pk-ink-dim`, `--pk-border-strong`, `--pk-lime-edge`, `--pk-magenta-edge`, `--pk-amber-edge`,",
  "`--pk-cyan-edge`, `--pk-violet-edge` (J16). No file changes for them.",
  "",
  "## What the tool prints, file by file",
  "",
  "The counts are from the verified run, after batch C: a read that was `var(--cyan-ink)` before",
  "the aliases went is `var(--pk-cyan-ink)` here, and is counted.",
  "",
  table(
    ["File", "Replacements"],
    Object.entries(expected).map(([file, counts]) => [
      cell(file),
      Object.entries(counts)
        .map(([name, count]) => `${cell(name)} ${count}`)
        .join(", "),
    ]),
  ),
  "",
  "## The token file's own edits",
  "",
  "### Task 15, `maps/15-styles-tokens.json`",
  "",
  table(["Goes", "Comes", "Times"], edits("15-styles-tokens")),
  "",
  "### Task 22, `maps/22-styles.json`, `maps/22-chart.json`, `maps/22-levels.json`",
  "",
  table(
    ["Goes", "Comes", "Times"],
    [...edits("22-styles"), ...edits("22-chart"), ...edits("22-levels")],
  ),
  "",
].join("\n");
writeFileSync(path.join(HERE, "../mapping-legacy-tokens.md"), legacy);

