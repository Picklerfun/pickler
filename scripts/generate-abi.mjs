#!/usr/bin/env node
/**
 * Foundry artifacts -> packages/chain/src/abi/. Never hand-edit the output.
 *
 * `packages/chain` is the public boundary for on-chain artifacts and its instructions require
 * ABIs to come from the compiler rather than being copied by hand. Run `npm run contracts:abi`
 * after any contract change; CI re-runs it and fails on a diff, so a committed ABI can never
 * describe a contract that no longer exists.
 *
 * Each file also exports a sha256 of its ABI. The indexer and the event decoder record that
 * hash alongside decoded logs, so a log decoded under one ABI version stays interpretable
 * after the contract changes.
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outputDirectory = join(root, "packages/chain/src/abi");

/**
 * Contracts whose ABI is part of the public interface. Add a contract here when external
 * consumers — the indexer, the API, a third-party integrator — need to decode or call it.
 */
const CONTRACTS = [
  "PicklerCurveMath",
  "PicklerPreset",
  "PicklerAgentToken",
  "PicklerLaunchFactory",
  "PicklerBondingCurve",
  "PicklerCurveDeployer",
  "PicklerGraduationAdapterV4",
  "PicklerGraduationAdapterV4V2",
  "PicklerCurveDeployerV4V2",
  "PicklerLiquidityLockerV2",
  "IUniswapV4Read",
  "IUniswapV4Router",
  "PicklerLiquidityLocker",
  "PicklerFeeEscrow",
  "PicklerFeeEscrowV2",
  "PicklerCurveDeployerKuru",
  "PicklerGraduationAdapterKuru",
  "PicklerKuruLiquidityLocker",
  "PicklerKuruPositionVault",
  "PicklerKuruPolicy",
  "IKuruAccountCore",
  "IKuruSpotRouter",
  "IKuruOrderBook",
];

rmSync(outputDirectory, { recursive: true, force: true });
mkdirSync(outputDirectory, { recursive: true });

const exports = [];

for (const name of CONTRACTS) {
  const sourceName = name.startsWith("IKuru") ? "IKuruPassive" : name;
  const artifactPath = join(root, "contracts/out", `${sourceName}.sol`, `${name}.json`);

  let artifact;
  try {
    artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
  } catch (cause) {
    throw new Error(
      `No compiler artifact for ${name} at ${artifactPath}. Run "npm run contracts:build" first.`,
      { cause },
    );
  }

  const abi = JSON.stringify(artifact.abi, null, 2);
  const abiHash = createHash("sha256").update(abi).digest("hex");

  const contents = `// Generated by scripts/generate-abi.mjs. Do not edit.
export const ${name}Abi = ${abi} as const;

export const ${name}AbiHash = "${abiHash}";
`;

  writeFileSync(join(outputDirectory, `${name}.ts`), contents);
  // packages/chain is consumed as TypeScript source and imports without extensions.
  // A ".js" specifier here resolves under Node but not under the web app's bundler.
  exports.push(`export * from "./${name}";`);
}

writeFileSync(
  join(outputDirectory, "index.ts"),
  `// Generated by scripts/generate-abi.mjs. Do not edit.\n${exports.join("\n")}\n`,
);

console.log(`Generated ${CONTRACTS.length} ABI file(s) into packages/chain/src/abi/`);
